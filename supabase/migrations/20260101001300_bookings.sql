-- =============================================================================
-- 13 · Bookings
-- =============================================================================
-- The book the front desk works from:
--
--   bookings            · one reservation: a renter, a window, a status
--   booking_line_items  · what that reservation holds: a product, and optionally
--                         the physical unit that goes out
--
-- Availability is derived, never stored. No write here touches
-- `products.inventory_quantity` or `assets.status`; what is out is what the line
-- items say, and `asset_availability` answers the question the board asks. That
-- is the same contract migration 04 states for the fleet, and it is why a unit
-- that comes back early frees itself the moment the desk marks it returned.
--
-- Two rows may never hold the same unit over overlapping days. That is an
-- exclusion constraint rather than a trigger: it holds under concurrent inserts,
-- which is exactly when two people book the same tandem.
--
-- Windows are half-open — `[starts_on, ends_on)` — everywhere: in the constraint,
-- in `check_asset_availability()` and in `lib/bookings.ts`. A booking that ends
-- on the 5th does not include the 5th, so a same-day handover is legal and
-- `ends_on > starts_on` is the only date rule needed.
-- =============================================================================

-- -----------------------------------------------------------------------------
-- Enums
-- -----------------------------------------------------------------------------
-- Complete on creation, like `asset_status`: PostgreSQL requires a new enum
-- value to commit before another statement may use it, so growing either ladder
-- later costs a migration of its own.
--
--   pending   · taken, not yet promised to a unit
--   confirmed · promised, waiting for the day
--   out       · the unit is with the renter
--   returned  · came back; the history stays readable
--   cancelled · called off; the lines stop holding their units
do $$
begin
  if not exists (select 1 from pg_type where typname = 'booking_status') then
    create type public.booking_status as enum (
      'pending',
      'confirmed',
      'out',
      'returned',
      'cancelled'
    );
  end if;
end
$$;

-- `staff` is a reservation somebody at the desk typed in; `api` is one a renter
-- client made. The column exists now so the renter API does not need a migration
-- to say where a booking came from.
do $$
begin
  if not exists (select 1 from pg_type where typname = 'booking_channel') then
    create type public.booking_channel as enum ('staff', 'api');
  end if;
end
$$;

-- -----------------------------------------------------------------------------
-- btree_gist
-- -----------------------------------------------------------------------------
-- An exclusion constraint may only mix `&&` on a range with `=` on plain
-- columns when GiST knows how to compare those columns. `btree_gist` supplies
-- that for uuid, and Supabase ships the extension.
create extension if not exists btree_gist;

-- -----------------------------------------------------------------------------
-- bookings
-- -----------------------------------------------------------------------------
create table if not exists public.bookings (
  id uuid primary key default gen_random_uuid(),
  company_id uuid not null references public.companies (id) on delete cascade,
  -- The number the desk and the renter quote at each other, generated by the
  -- action. Unique inside the workspace rather than globally: two shops may both
  -- have BK-7F3K2Q, and neither should care.
  reference text not null check (reference ~ '^BK-[0-9A-Z]{6}$'),
  customer_id uuid not null,
  status public.booking_status not null default 'pending',
  channel public.booking_channel not null default 'staff',
  -- Whole days, half-open. `[2026-03-01, 2026-03-05)` is a four-day hire that
  -- leaves the unit free on the 5th.
  starts_on date not null,
  ends_on date not null,
  currency text not null default 'usd' check (currency ~ '^[a-z]{3}$'),
  notes text,
  -- Who took the booking. Deleting that person's account keeps the booking: the
  -- shop still has a unit to hand over.
  created_by uuid references public.profiles (id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (company_id, reference),
  -- The target of `booking_line_items`' composite key.
  unique (company_id, id),
  constraint bookings_window check (ends_on > starts_on),
  -- A renter with history is not deletable: the bookings are the reason the row
  -- existed. The manager-facing action turns the refusal into a sentence.
  constraint bookings_customer_fk
    foreign key (company_id, customer_id)
    references public.customers (company_id, id)
    on delete restrict
);

comment on column public.bookings.starts_on is
  'First day the unit is out. Inclusive.';
comment on column public.bookings.ends_on is
  'Day the unit comes back. Exclusive: the unit is free again on this date.';

create index if not exists bookings_company_window_idx
  on public.bookings (company_id, starts_on desc);
create index if not exists bookings_company_customer_idx
  on public.bookings (company_id, customer_id);
create index if not exists bookings_company_status_idx
  on public.bookings (company_id, status);

drop trigger if exists bookings_set_updated_at on public.bookings;
create trigger bookings_set_updated_at
  before update on public.bookings
  for each row execute function public.set_updated_at();


-- -----------------------------------------------------------------------------
-- booking_line_items
-- -----------------------------------------------------------------------------
-- One row per thing the booking holds. A line may name only a product — the shop
-- has promised "a gravel bike" and will decide which one on the morning — and
-- the empty `asset_id` is what keeps that legal.
create table if not exists public.booking_line_items (
  id uuid primary key default gen_random_uuid(),
  company_id uuid not null references public.companies (id) on delete cascade,
  booking_id uuid not null,
  product_id uuid,
  -- The physical unit, when the desk has picked one. NULL means "not allocated
  -- yet", which never conflicts with anything.
  asset_id uuid,
  -- Who rides it, when that is not the person who booked. NULL means the booker.
  rider_id uuid,
  quantity integer not null default 1 check (quantity > 0),
  -- Money in the currency's minor unit, like every other price in the schema.
  unit_price_cents integer not null default 0 check (unit_price_cents >= 0),
  -- Copied from the booking by `booking_line_items_sync`, never taken from the
  -- form: the exclusion constraint is only trustworthy if the window it reads is
  -- the booking's own.
  starts_on date not null,
  ends_on date not null,
  -- Also copied from the parent's status. A cancelled booking keeps its lines —
  -- the history is worth reading — but stops holding a unit, which is what makes
  -- the constraint's `where` clause mean "still reserved".
  blocks_stock boolean not null default true,
  created_at timestamptz not null default now(),
  constraint booking_line_items_window check (ends_on > starts_on),
  constraint booking_line_items_booking_fk
    foreign key (company_id, booking_id)
    references public.bookings (company_id, id)
    on delete cascade,
  constraint booking_line_items_product_fk
    foreign key (company_id, product_id)
    references public.products (company_id, id)
    on delete set null (product_id),
  constraint booking_line_items_asset_fk
    foreign key (company_id, asset_id)
    references public.assets (company_id, id)
    on delete set null (asset_id),
  constraint booking_line_items_rider_fk
    foreign key (company_id, rider_id)
    references public.customers (company_id, id)
    on delete set null (rider_id)
);

comment on column public.booking_line_items.blocks_stock is
  'True while the parent booking still reserves this unit. Written by triggers only.';

create index if not exists booking_line_items_booking_idx
  on public.booking_line_items (company_id, booking_id);
create index if not exists booking_line_items_asset_idx
  on public.booking_line_items (company_id, asset_id);

-- The double-booking guard.
--
-- `uuid[]` on `bookings` could not take a GiST `&&`, so the constraint has to
-- sit where the single asset is. The `where` clause is what lets a cancelled
-- booking keep its rows without keeping the unit.
--
-- Dropped first so the file is re-runnable, like the triggers around it.
alter table public.booking_line_items
  drop constraint if exists booking_line_items_no_overlap;

alter table public.booking_line_items
  add constraint booking_line_items_no_overlap
  exclude using gist (
    company_id with =,
    asset_id with =,
    daterange(starts_on, ends_on, '[)') with &&
  ) where (asset_id is not null and blocks_stock);

-- -----------------------------------------------------------------------------
-- Which statuses hold a unit
-- -----------------------------------------------------------------------------
-- One place in SQL decides it, and `lib/bookings.ts` keeps the same list so the
-- UI can predict what the database will do. `tests/db/schema.test.ts` reads this
-- list and fails if the two drift.
--
--   returned  · came back, the unit is free
--   cancelled · called off, the unit is free
--   pending, confirmed, out · still promised
create or replace function public.booking_blocks_stock(
  target_status public.booking_status
)
returns boolean
language sql
immutable
as $$
  select target_status in ('pending', 'confirmed', 'out');
$$;

comment on function public.booking_blocks_stock(public.booking_status) is
  'True while a booking in this status still reserves the units on its lines.';

-- -----------------------------------------------------------------------------
-- booking_line_items_sync · the line follows its booking
-- -----------------------------------------------------------------------------
-- The window and the `blocks_stock` flag are never what a client sends; they are
-- properties of the booking. Writing them here means a hand-written insert
-- cannot sneak a unit into a window the booking never had.
--
-- SECURITY DEFINER because the read must not depend on the caller's RLS grants on
-- `bookings`.
create or replace function public.booking_line_items_sync()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  parent_starts_on date;
  parent_ends_on date;
  parent_status public.booking_status;
begin
  select b.starts_on, b.ends_on, b.status
    into parent_starts_on, parent_ends_on, parent_status
    from public.bookings b
   where b.id = new.booking_id
     and b.company_id = new.company_id;

  if not found then
    raise exception 'A booking line must belong to a booking of the same company'
      using errcode = 'foreign_key_violation';
  end if;

  new.starts_on := parent_starts_on;
  new.ends_on := parent_ends_on;
  new.blocks_stock := public.booking_blocks_stock(parent_status);

  return new;
end;
$$;

drop trigger if exists booking_line_items_sync on public.booking_line_items;
create trigger booking_line_items_sync
  before insert or update on public.booking_line_items
  for each row execute function public.booking_line_items_sync();

-- -----------------------------------------------------------------------------
-- bookings_propagate_dates · the booking drags its lines with it
-- -----------------------------------------------------------------------------
-- Moving a booking, or marking it returned, has to move every line in the same
-- statement — otherwise the constraint would still see the old window and a
-- cancellation would keep the unit reserved.
--
-- The update fires `booking_line_items_sync` for each row, which recomputes the
-- same values and is therefore a no-op. If the new window collides with another
-- booking, the exclusion constraint refuses the whole update: a date change that
-- double-books fails as loudly as an insert.
create or replace function public.bookings_propagate_dates()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if new.starts_on is not distinct from old.starts_on
     and new.ends_on is not distinct from old.ends_on
     and new.status is not distinct from old.status then
    return new;
  end if;

  update public.booking_line_items l
     set starts_on = new.starts_on,
         ends_on = new.ends_on,
         blocks_stock = public.booking_blocks_stock(new.status)
   where l.booking_id = new.id
     and l.company_id = new.company_id;

  return new;
end;
$$;

drop trigger if exists bookings_propagate_dates on public.bookings;
create trigger bookings_propagate_dates
  after update of starts_on, ends_on, status on public.bookings
  for each row execute function public.bookings_propagate_dates();

-- -----------------------------------------------------------------------------
-- check_asset_availability · the advisory answer
-- -----------------------------------------------------------------------------
-- The constraint is the guarantee; this is what lets `assignAsset` say "that unit
-- is already out on those dates" instead of handing back a raw 23P01. It counts
-- the blocking lines that overlap the window, so `0` means the unit is free.
--
-- SECURITY DEFINER with an empty search_path: the caller has the section on, but
-- the answer must not vary with the RLS the planner happens to apply.
create or replace function public.check_asset_availability(
  target_company_id uuid,
  target_asset_id uuid,
  from_date date,
  to_date date
)
returns integer
language sql
stable
security definer
set search_path = ''
as $$
  select count(*)::integer
  from public.booking_line_items l
  where l.company_id = target_company_id
    and l.asset_id = target_asset_id
    and l.blocks_stock
    and daterange(l.starts_on, l.ends_on, '[)')
        && daterange(from_date, to_date, '[)');
$$;

comment on function public.check_asset_availability(uuid, uuid, date, date) is
  'How many blocking booking lines overlap the window. Advisory: the exclusion constraint decides.';

-- -----------------------------------------------------------------------------
-- asset_availability
-- -----------------------------------------------------------------------------
-- What is out, and when. Derived from the lines every time it is read — there is
-- no stored count anywhere — so it cannot disagree with the bookings above it.
--
-- `security_invoker = true` keeps the view on the caller's side of RLS: without
-- it a view runs as its owner and would hand one workspace another's bookings.
create or replace view public.asset_availability
with (security_invoker = true)
as
select
  l.company_id,
  l.asset_id,
  l.booking_id,
  l.id as line_item_id,
  l.starts_on,
  l.ends_on,
  daterange(l.starts_on, l.ends_on, '[)') as period
from public.booking_line_items l
where l.asset_id is not null
  and l.blocks_stock;

