-- Supabase grants EXECUTE on new `public` functions to `anon` explicitly, so
-- every helper is revoked from it by name — the rule migrations 01–04 follow.

-- Predicates a session may call.
revoke all on function public.booking_blocks_stock(public.booking_status) from public, anon;
grant execute on function public.booking_blocks_stock(public.booking_status) to authenticated, service_role;

revoke all on function public.check_asset_availability(uuid, uuid, date, date) from public, anon;
grant execute on function public.check_asset_availability(uuid, uuid, date, date) to authenticated, service_role;

-- Trigger-only functions: no client role may execute these. PostgreSQL does not
-- check EXECUTE when firing a trigger, so this changes nothing for the triggers.
revoke all on function public.booking_line_items_sync() from public, anon, authenticated;
revoke all on function public.bookings_propagate_dates() from public, anon, authenticated;

grant execute on function public.booking_line_items_sync() to service_role;
grant execute on function public.bookings_propagate_dates() to service_role;

-- The view is read through RLS on the table underneath (security_invoker), but
-- nothing anonymous has any business listing a workspace's calendar.
revoke all on public.asset_availability from anon;
grant select on public.asset_availability to authenticated, service_role;

